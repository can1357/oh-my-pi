#!/usr/bin/env bun
/**
 * Generates Bazel clippy policy from `[workspace.lints]` in `Cargo.toml` so
 * the cargo lint policy and the Bazel clippy aspect cannot drift.
 *
 * `bazel/clippy.bazelrc` is the `--config=clippy-strict` flag list. Opted-in
 * crates also attach the same policy via `lint_config = "//bazel/lints:workspace_lints"`
 * (`bazel/lints/BUILD.bazel`). The clippy aspect applies `lint_config` before
 * command-line flags, so `--config=clippy` (`-Dwarnings`) still enforces the
 * workspace policy when a crate is missing from CI's strict query.
 *
 * Emission mirrors rustc lint-level resolution: rustc entries first, then
 * clippy entries — negative `priority` values (the lint groups) before
 * per-lint overrides, alphabetical within each tier.
 *
 * Usage:
 *   bun scripts/gen-clippy-bazelrc.ts                 # rewrite generated files
 *   bun scripts/gen-clippy-bazelrc.ts --check         # exit 1 when stale or uncovered
 *   bun scripts/gen-clippy-bazelrc.ts --coverage      # coverage only
 *   bun scripts/gen-clippy-bazelrc.ts --root <dir>    # operate on another tree
 */
import { isEnoent } from "@oh-my-pi/pi-utils/fs-error";
import * as fs from "node:fs/promises";
import * as path from "node:path";

type LintLevel = "allow" | "warn" | "deny" | "forbid";
type LintEntry = LintLevel | { level: LintLevel; priority?: number };
type LintTable = Record<string, LintEntry>;

interface WorkspaceLints {
	rust: LintTable;
	clippy: LintTable;
}

interface CoverageGap {
	crate: string;
	detail: string;
}

interface Coverage {
	covered: string[];
	gaps: CoverageGap[];
}

const FLAG_BY_LEVEL: Record<LintLevel, string> = { allow: "A", warn: "W", deny: "D", forbid: "F" };
const WORKSPACE_LINTS_LABEL = "//bazel/lints:workspace_lints";
const CLIPPY_RULES = ["rust_library", "rust_shared_library", "rust_binary"] as const;
const COVERAGE_PREFIX = "workspace-lint-coverage:";
const GAP_PREFIX = "workspace-lint-coverage-gap:";

const repoRoot = path.join(import.meta.dir, "..");

function normalize(entry: LintEntry): { level: LintLevel; priority: number } {
	if (typeof entry === "string") return { level: entry, priority: 0 };
	return { level: entry.level, priority: entry.priority ?? 0 };
}

/** Lint names ordered by ascending priority tier, alphabetical within a tier. */
function orderedNames(table: LintTable): string[] {
	return Object.keys(table).sort((a, b) => {
		const pa = normalize(table[a]).priority;
		const pb = normalize(table[b]).priority;
		if (pa !== pb) return pa - pb;
		return a < b ? -1 : a > b ? 1 : 0;
	});
}

function flagLines(table: LintTable, prefix: string): string[] {
	return orderedNames(table).map(name => {
		const { level } = normalize(table[name]);
		return `build:clippy-strict --@rules_rust//rust/settings:clippy_flag=-${FLAG_BY_LEVEL[level]}${prefix}${name}`;
	});
}

function renderClippyBazelrc(lints: WorkspaceLints): string {
	const lines = [
		"# Generated by scripts/gen-clippy-bazelrc.ts from [workspace.lints] in Cargo.toml.",
		"# Do not edit by hand; run `bun run gen:clippy` after changing the lint policy.",
		"# Applies only to crates that opt in via `[lints] workspace = true`.",
		"# Opted-in crates attach the same policy with",
		`# \`lint_config = "${WORKSPACE_LINTS_LABEL}"\` (bazel/lints/BUILD.bazel), so`,
		"# `--config=clippy` still enforces it when the CI strict query omits a crate.",
		"# The lint policy is authored against the rustup nightly, which may know",
		"# lints the pinned bazel toolchain predates; those names must not become",
		"# hard errors under the clippy aspect's -Dwarnings.",
		"build:clippy-strict --@rules_rust//rust/settings:clippy_flag=-Aunknown_lints",
		...flagLines(lints.rust, ""),
		...flagLines(lints.clippy, "clippy::"),
	];
	return `${lines.join("\n")}\n`;
}

function starlarkDict(entries: readonly (readonly [string, LintLevel])[]): string {
	const lines = entries.map(([name, level]) => `        "${name}": "${level}",`);
	return `{\n${lines.join("\n")}\n    }`;
}

function renderLintsBuild(lints: WorkspaceLints): string {
	const rustEntries: (readonly [string, LintLevel])[] = [
		["unknown_lints", "allow"],
		...orderedNames(lints.rust).map(name => [name, normalize(lints.rust[name]).level] as const),
	];
	const clippyEntries = orderedNames(lints.clippy).map(name => [name, normalize(lints.clippy[name]).level] as const);
	return `# Generated by scripts/gen-clippy-bazelrc.ts from [workspace.lints] in Cargo.toml.
# Do not edit by hand; run \`bun run gen:clippy\` after changing the lint policy.
# Dict order is load-bearing: group lints (negative priority) precede per-lint
# overrides. The clippy aspect emits the clippy dict, then the rustc dict, then
# command-line flags. \`--config=clippy\` appends only \`-Dwarnings\`, which does
# not override an earlier explicit allow.

load("@rules_rust//rust:defs.bzl", "rust_lint_config")

package(default_visibility = ["//visibility:public"])

# buildifier: disable=unsorted-dict-items
rust_lint_config(
    name = "workspace_lints",
    rustc = ${starlarkDict(rustEntries)},
    clippy = ${starlarkDict(clippyEntries)},
)
`;
}

async function readText(filePath: string): Promise<string | null> {
	try {
		return await Bun.file(filePath).text();
	} catch (err) {
		if (isEnoent(err)) return null;
		throw err;
	}
}

async function loadWorkspaceLints(root: string): Promise<WorkspaceLints> {
	const cargoPath = path.join(root, "Cargo.toml");
	const text = await readText(cargoPath);
	if (text == null) {
		throw new Error(`${cargoPath} is missing`);
	}
	const cargo = Bun.TOML.parse(text) as {
		workspace?: { lints?: { rust?: LintTable; clippy?: LintTable } };
	};
	const lints = cargo.workspace?.lints;
	if (!lints?.clippy) {
		throw new Error(`${cargoPath} has no [workspace.lints.clippy] table`);
	}
	return { rust: lints.rust ?? {}, clippy: lints.clippy };
}

function optsIntoWorkspaceLints(cargoToml: string): boolean {
	const parsed = Bun.TOML.parse(cargoToml) as { lints?: { workspace?: unknown } };
	return parsed.lints?.workspace === true;
}

/** Rule-call bodies for the kinds CI clippy builds. Comments and strings are skipped. */
function clippyRuleCalls(buildText: string): { kind: string; body: string }[] {
	const calls: { kind: string; body: string }[] = [];
	const pattern = new RegExp(`^[ \\t]*(?:${CLIPPY_RULES.join("|")})\\(`, "gm");
	for (const match of buildText.matchAll(pattern)) {
		const open = match.index + match[0].length - 1;
		const body = callBody(buildText, open);
		if (body == null) {
			calls.push({ kind: match[0].slice(0, -1), body: "" });
			continue;
		}
		calls.push({ kind: match[0].slice(0, -1), body });
	}
	return calls;
}

function callBody(text: string, openParen: number): string | null {
	let depth = 0;
	let quote: string | null = null;
	for (let i = openParen; i < text.length; i++) {
		const char = text[i];
		if (quote != null) {
			if (char === "\\") {
				i++;
				continue;
			}
			if (char === quote) quote = null;
			continue;
		}
		if (char === '"' || char === "'") {
			quote = char;
			continue;
		}
		if (char === "#") {
			const newline = text.indexOf("\n", i);
			i = newline === -1 ? text.length : newline;
			continue;
		}
		if (char === "(") depth++;
		else if (char === ")") {
			depth--;
			if (depth === 0) return text.slice(openParen, i + 1);
		}
	}
	return null;
}

function hasWorkspaceLintConfig(callBodyText: string): boolean {
	return new RegExp(`lint_config\\s*=\\s*"${WORKSPACE_LINTS_LABEL.replaceAll("/", "\\/")}"`).test(callBodyText);
}

function targetName(callBodyText: string): string {
	return /name\s*=\s*"([^"]+)"/.exec(callBodyText)?.[1] ?? "<unnamed>";
}

async function checkCoverage(root: string): Promise<Coverage> {
	const cratesDir = path.join(root, "crates");
	let entries: string[];
	try {
		entries = await fs.readdir(cratesDir);
	} catch (err) {
		if (isEnoent(err)) return { covered: [], gaps: [] };
		throw err;
	}
	const covered: string[] = [];
	const gaps: CoverageGap[] = [];
	for (const name of entries.sort()) {
		const crateDir = path.join(cratesDir, name);
		if (!(await fs.stat(crateDir)).isDirectory()) continue;
		const cargoPath = path.join(crateDir, "Cargo.toml");
		const cargoToml = await readText(cargoPath);
		if (cargoToml == null) continue;
		if (!optsIntoWorkspaceLints(cargoToml)) continue;

		const buildPath = path.join(crateDir, "BUILD.bazel");
		const buildText = await readText(buildPath);
		if (buildText == null) {
			gaps.push({ crate: name, detail: "has no BUILD.bazel" });
			continue;
		}
		const calls = clippyRuleCalls(buildText);
		if (calls.length === 0) {
			gaps.push({
				crate: name,
				detail: `has no ${CLIPPY_RULES.join(", ")} target`,
			});
			continue;
		}
		let crateCovered = true;
		for (const call of calls) {
			if (call.body.length === 0 || !hasWorkspaceLintConfig(call.body)) {
				crateCovered = false;
				gaps.push({
					crate: name,
					detail: `${call.kind} "${targetName(call.body)}" is missing lint_config = "${WORKSPACE_LINTS_LABEL}"`,
				});
			}
		}
		if (crateCovered) covered.push(name);
	}
	return { covered, gaps };
}

function coverageLine(covered: readonly string[]): string {
	return covered.length === 0 ? `${COVERAGE_PREFIX}` : `${COVERAGE_PREFIX} ${covered.join(" ")}`;
}

function reportGaps(coverage: Coverage): void {
	for (const gap of coverage.gaps) {
		console.error(`${GAP_PREFIX} ${gap.crate} ${gap.detail}`);
	}
}

interface Args {
	check: boolean;
	coverageOnly: boolean;
	root: string;
}

function parseArgs(argv: string[]): Args {
	const rootFlag = argv.indexOf("--root");
	let root = repoRoot;
	if (rootFlag !== -1) {
		const value = argv[rootFlag + 1];
		if (value == null || value.startsWith("--")) {
			console.error("--root requires a directory");
			process.exit(2);
		}
		root = path.resolve(value);
	}
	return {
		check: argv.includes("--check"),
		coverageOnly: argv.includes("--coverage"),
		root,
	};
}

const args = parseArgs(process.argv.slice(2));

if (args.coverageOnly) {
	const coverage = await checkCoverage(args.root);
	if (coverage.gaps.length > 0) {
		reportGaps(coverage);
		process.exit(1);
	}
	console.log(coverageLine(coverage.covered));
	process.exit(0);
}

const lints = await loadWorkspaceLints(args.root);
const expected = {
	clippyBazelrc: renderClippyBazelrc(lints),
	lintsBuild: renderLintsBuild(lints),
};
const outputs = [
	{
		label: "bazel/clippy.bazelrc",
		path: path.join(args.root, "bazel", "clippy.bazelrc"),
		text: expected.clippyBazelrc,
	},
	{
		label: "bazel/lints/BUILD.bazel",
		path: path.join(args.root, "bazel", "lints", "BUILD.bazel"),
		text: expected.lintsBuild,
	},
];
const coverage = await checkCoverage(args.root);

if (args.check) {
	let stale = false;
	for (const output of outputs) {
		const current = (await readText(output.path)) ?? "";
		if (current !== output.text) {
			stale = true;
			console.error(
				`${output.label} is stale relative to [workspace.lints] in Cargo.toml.\n` +
					"Run `bun run gen:clippy` and commit the result.",
			);
		}
	}
	if (coverage.gaps.length > 0) reportGaps(coverage);
	if (stale || coverage.gaps.length > 0) process.exit(1);
	for (const output of outputs) {
		console.log(`${output.label} is in sync with Cargo.toml.`);
	}
	console.log(coverageLine(coverage.covered));
} else {
	let wrote = false;
	for (const output of outputs) {
		const current = (await readText(output.path)) ?? "";
		if (current === output.text) continue;
		await Bun.write(output.path, output.text);
		console.log(`Wrote ${output.label}.`);
		wrote = true;
	}
	if (!wrote) console.log("bazel clippy policy already up to date.");
	if (coverage.gaps.length > 0) {
		reportGaps(coverage);
		process.exit(1);
	}
}
