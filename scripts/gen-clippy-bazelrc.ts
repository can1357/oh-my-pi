#!/usr/bin/env bun
/**
 * Generates Bazel clippy policy from `[workspace.lints]` in `Cargo.toml` so
 * the cargo lint policy and the Bazel clippy aspect cannot drift.
 *
 * `bazel/clippy.bazelrc` is the `--config=clippy-strict` flag list. Opted-in
 * crates also attach the same policy via `lint_config = "//bazel/lints:workspace_lints"`
 * (`bazel/lints/BUILD.bazel`). The clippy aspect applies `lint_config` before
 * command-line flags, so `--config=clippy` (`-Dwarnings`) enforces the
 * workspace policy on any target it schedules. Coverage checks also verify
 * every opted-in library and binary is scheduled by `.github/workflows/ci.yml`.
 *
 * Emission mirrors rustc lint-level resolution: rustc entries first, then
 * clippy entries — negative `priority` values (the lint groups) before
 * per-lint overrides, alphabetical within each tier.
 *
 * Usage:
 *   bun scripts/gen-clippy-bazelrc.ts                 # rewrite generated files
 *   bun scripts/gen-clippy-bazelrc.ts --check         # exit 1 when stale or uncovered
 *   bun scripts/gen-clippy-bazelrc.ts --coverage      # coverage only
 *   bun scripts/gen-clippy-bazelrc.ts --root <dir>    # operate on another tree
 */
import { isEnoent } from "@oh-my-pi/pi-utils/fs-error";
import * as fs from "node:fs/promises";
import * as path from "node:path";

type LintLevel = "allow" | "warn" | "deny" | "forbid";
type LintEntry = LintLevel | { level: LintLevel; priority?: number };
type LintTable = Record<string, LintEntry>;

interface WorkspaceLints {
	rust: LintTable;
	clippy: LintTable;
}

interface CoverageGap {
	crate: string;
	detail: string;
}

interface Coverage {
	covered: string[];
	gaps: CoverageGap[];
}

const FLAG_BY_LEVEL: Record<LintLevel, string> = { allow: "A", warn: "W", deny: "D", forbid: "F" };
const WORKSPACE_LINTS_LABEL = "//bazel/lints:workspace_lints";
const CLIPPY_RULES = ["rust_library", "rust_shared_library", "rust_binary"] as const;
type ClippyRuleKind = (typeof CLIPPY_RULES)[number];
const CLIPPY_RULE_SET = new Set<string>(CLIPPY_RULES);

interface RuleCall {
	kind: ClippyRuleKind;
	/** Top-level keyword arguments whose values are plain string literals; null if unterminated. */
	stringAttrs: Map<string, string> | null;
}

type CiClippyTargetMatcher = (crate: string, kind: ClippyRuleKind, target: string) => boolean;
const COVERAGE_PREFIX = "workspace-lint-coverage:";
const GAP_PREFIX = "workspace-lint-coverage-gap:";

const repoRoot = path.join(import.meta.dir, "..");

function normalize(entry: LintEntry): { level: LintLevel; priority: number } {
	if (typeof entry === "string") return { level: entry, priority: 0 };
	return { level: entry.level, priority: entry.priority ?? 0 };
}

/** Lint names ordered by ascending priority tier, alphabetical within a tier. */
function orderedNames(table: LintTable): string[] {
	return Object.keys(table).sort((a, b) => {
		const pa = normalize(table[a]).priority;
		const pb = normalize(table[b]).priority;
		if (pa !== pb) return pa - pb;
		return a < b ? -1 : a > b ? 1 : 0;
	});
}

function flagLines(table: LintTable, prefix: string): string[] {
	return orderedNames(table).map(name => {
		const { level } = normalize(table[name]);
		return `build:clippy-strict --@rules_rust//rust/settings:clippy_flag=-${FLAG_BY_LEVEL[level]}${prefix}${name}`;
	});
}

function renderClippyBazelrc(lints: WorkspaceLints): string {
	const lines = [
		"# Generated by scripts/gen-clippy-bazelrc.ts from [workspace.lints] in Cargo.toml.",
		"# Do not edit by hand; run `bun run gen:clippy` after changing the lint policy.",
		"# Applies only to crates that opt in via `[lints] workspace = true`.",
		"# Opted-in crates attach the same policy with",
		`# \`lint_config = "${WORKSPACE_LINTS_LABEL}"\` (bazel/lints/BUILD.bazel), so`,
		"# `--config=clippy` still enforces it when the CI strict query omits a crate.",
		"# The lint policy is authored against the rustup nightly, which may know",
		"# lints the pinned bazel toolchain predates; those names must not become",
		"# hard errors under the clippy aspect's -Dwarnings.",
		"build:clippy-strict --@rules_rust//rust/settings:clippy_flag=-Aunknown_lints",
		...flagLines(lints.rust, ""),
		...flagLines(lints.clippy, "clippy::"),
	];
	return `${lines.join("\n")}\n`;
}

function starlarkDict(entries: readonly (readonly [string, LintLevel])[]): string {
	const lines = entries.map(([name, level]) => `        "${name}": "${level}",`);
	return `{\n${lines.join("\n")}\n    }`;
}

function renderLintsBuild(lints: WorkspaceLints): string {
	const rustEntries: (readonly [string, LintLevel])[] = [
		["unknown_lints", "allow"],
		...orderedNames(lints.rust).map(name => [name, normalize(lints.rust[name]).level] as const),
	];
	const clippyEntries = orderedNames(lints.clippy).map(name => [name, normalize(lints.clippy[name]).level] as const);
	return `# Generated by scripts/gen-clippy-bazelrc.ts from [workspace.lints] in Cargo.toml.
# Do not edit by hand; run \`bun run gen:clippy\` after changing the lint policy.
# Dict order is load-bearing: group lints (negative priority) precede per-lint
# overrides. The clippy aspect emits the clippy dict, then the rustc dict, then
# command-line flags. \`--config=clippy\` appends only \`-Dwarnings\`, which does
# not override an earlier explicit allow.

load("@rules_rust//rust:defs.bzl", "rust_lint_config")

package(default_visibility = ["//visibility:public"])

# buildifier: disable=unsorted-dict-items
rust_lint_config(
    name = "workspace_lints",
    rustc = ${starlarkDict(rustEntries)},
    clippy = ${starlarkDict(clippyEntries)},
)
`;
}

async function readText(filePath: string): Promise<string | null> {
	try {
		return await Bun.file(filePath).text();
	} catch (err) {
		if (isEnoent(err)) return null;
		throw err;
	}
}

async function loadWorkspaceLints(root: string): Promise<WorkspaceLints> {
	const cargoPath = path.join(root, "Cargo.toml");
	const text = await readText(cargoPath);
	if (text == null) {
		throw new Error(`${cargoPath} is missing`);
	}
	const cargo = Bun.TOML.parse(text) as {
		workspace?: { lints?: { rust?: LintTable; clippy?: LintTable } };
	};
	const lints = cargo.workspace?.lints;
	if (!lints?.clippy) {
		throw new Error(`${cargoPath} has no [workspace.lints.clippy] table`);
	}
	return { rust: lints.rust ?? {}, clippy: lints.clippy };
}

function optsIntoWorkspaceLints(cargoToml: string): boolean {
	const parsed = Bun.TOML.parse(cargoToml) as { lints?: { workspace?: unknown } };
	return parsed.lints?.workspace === true;
}

function isIdentStart(ch: string): boolean {
	return (ch >= "A" && ch <= "Z") || (ch >= "a" && ch <= "z") || ch === "_";
}

function isIdentPart(ch: string): boolean {
	return isIdentStart(ch) || (ch >= "0" && ch <= "9");
}

function skipLineComment(text: string, pos: number, end: number): number {
	const newline = text.indexOf("\n", pos);
	return newline === -1 || newline >= end ? end : newline + 1;
}

function parseStarlarkString(text: string, pos: number, end: number): { value: string; end: number } | null {
	let i = pos;
	let raw = false;
	if (i + 1 < end && (text[i] === "r" || text[i] === "R") && (text[i + 1] === '"' || text[i + 1] === "'")) {
		raw = true;
		i++;
	}
	if (i >= end) return null;
	const quote = text[i];
	if (quote !== '"' && quote !== "'") return null;

	const triple = i + 2 < end && text[i + 1] === quote && text[i + 2] === quote;
	i += triple ? 3 : 1;
	let value = "";
	while (i < end) {
		const ch = text[i];
		if (!triple && ch === "\n") return null;
		if (ch === "\\") {
			if (i + 1 >= end) return null;
			const next = text[i + 1];
			if (raw) {
				value += ch + next;
			} else if (next === "n") {
				value += "\n";
			} else if (next === "r") {
				value += "\r";
			} else if (next === "t") {
				value += "\t";
			} else {
				value += next;
			}
			i += 2;
			continue;
		}
		if (triple) {
			if (i + 2 < end && text[i] === quote && text[i + 1] === quote && text[i + 2] === quote) {
				return { value, end: i + 3 };
			}
		} else if (ch === quote) {
			return { value, end: i + 1 };
		}
		value += ch;
		i++;
	}
	return null;
}

function skipStarlarkTrivia(text: string, pos: number, end: number): number {
	let i = pos;
	while (i < end) {
		const ch = text[i];
		if (ch === " " || ch === "\t" || ch === "\r" || ch === "\n") {
			i++;
			continue;
		}
		if (ch === "#") {
			i = skipLineComment(text, i, end);
			continue;
		}
		break;
	}
	return i;
}

function findMatchingParen(text: string, openParen: number): number {
	let depth = 0;
	let i = openParen;
	const end = text.length;
	while (i < end) {
		const ch = text[i];
		if (ch === "#") {
			i = skipLineComment(text, i, end);
			continue;
		}
		if (
			ch === '"' ||
			ch === "'" ||
			((ch === "r" || ch === "R") && i + 1 < end && (text[i + 1] === '"' || text[i + 1] === "'"))
		) {
			const lit = parseStarlarkString(text, i, end);
			if (lit == null) return -1;
			i = lit.end;
			continue;
		}
		if (ch === "(" || ch === "[" || ch === "{") {
			depth++;
		} else if (ch === ")" || ch === "]" || ch === "}") {
			depth--;
			if (depth === 0) return ch === ")" ? i : -1;
		} else if (isIdentStart(ch)) {
			while (i < end && isIdentPart(text[i])) i++;
			continue;
		}
		i++;
	}
	return -1;
}

/** Parses top-level keyword arguments whose values are plain Starlark string literals. */
function parseTopLevelStringAttrs(text: string, start: number, end: number): Map<string, string> {
	const attrs = new Map<string, string>();
	const segments: [number, number][] = [];
	let segStart = start;
	let depth = 0;
	let i = start;
	while (i < end) {
		const ch = text[i];
		if (ch === "#") {
			i = skipLineComment(text, i, end);
			continue;
		}
		if (
			ch === '"' ||
			ch === "'" ||
			((ch === "r" || ch === "R") && i + 1 < end && (text[i + 1] === '"' || text[i + 1] === "'"))
		) {
			const lit = parseStarlarkString(text, i, end);
			if (lit == null) return attrs;
			i = lit.end;
			continue;
		}
		if (ch === "(" || ch === "[" || ch === "{") {
			depth++;
		} else if (ch === ")" || ch === "]" || ch === "}") {
			depth = Math.max(0, depth - 1);
		} else if (ch === "," && depth === 0) {
			segments.push([segStart, i]);
			segStart = i + 1;
		} else if (isIdentStart(ch)) {
			while (i < end && isIdentPart(text[i])) i++;
			continue;
		}
		i++;
	}
	segments.push([segStart, end]);

	for (const [s, e] of segments) {
		let p = skipStarlarkTrivia(text, s, e);
		if (p >= e || !isIdentStart(text[p])) continue;
		const keyStart = p;
		while (p < e && isIdentPart(text[p])) p++;
		const key = text.slice(keyStart, p);
		p = skipStarlarkTrivia(text, p, e);
		if (p >= e || text[p] !== "=" || (p + 1 < e && text[p + 1] === "=")) continue;
		p = skipStarlarkTrivia(text, p + 1, e);
		const lit = parseStarlarkString(text, p, e);
		if (lit != null && skipStarlarkTrivia(text, lit.end, e) === e) {
			attrs.set(key, lit.value);
		} else {
			attrs.delete(key);
		}
	}
	return attrs;
}

/** Top-level rule calls for the kinds CI clippy builds, with parsed string attributes. */
function clippyRuleCalls(buildText: string): RuleCall[] {
	const calls: RuleCall[] = [];
	let depth = 0;
	let i = 0;
	let prevNonSpace = "";
	const end = buildText.length;
	while (i < end) {
		const ch = buildText[i];
		if (ch === "#") {
			i = skipLineComment(buildText, i, end);
			continue;
		}
		if (
			ch === '"' ||
			ch === "'" ||
			((ch === "r" || ch === "R") && i + 1 < end && (buildText[i + 1] === '"' || buildText[i + 1] === "'"))
		) {
			const lit = parseStarlarkString(buildText, i, end);
			i = lit == null ? end : lit.end;
			prevNonSpace = '"';
			continue;
		}
		if (ch === "(" || ch === "[" || ch === "{") {
			depth++;
			prevNonSpace = ch;
			i++;
			continue;
		}
		if (ch === ")" || ch === "]" || ch === "}") {
			depth = Math.max(0, depth - 1);
			prevNonSpace = ch;
			i++;
			continue;
		}
		if (isIdentStart(ch)) {
			const identStart = i;
			while (i < end && isIdentPart(buildText[i])) i++;
			const ident = buildText.slice(identStart, i);
			if (depth === 0 && prevNonSpace !== "." && CLIPPY_RULE_SET.has(ident)) {
				let open = i;
				while (open < end && (buildText[open] === " " || buildText[open] === "\t")) open++;
				if (open < end && buildText[open] === "(") {
					const close = findMatchingParen(buildText, open);
					if (close === -1) {
						calls.push({ kind: ident as ClippyRuleKind, stringAttrs: null });
						break;
					}
					calls.push({
						kind: ident as ClippyRuleKind,
						stringAttrs: parseTopLevelStringAttrs(buildText, open + 1, close),
					});
					i = close + 1;
					prevNonSpace = ")";
					continue;
				}
			}
			prevNonSpace = "a";
			continue;
		}
		if (ch !== " " && ch !== "\t" && ch !== "\r" && ch !== "\n") {
			prevNonSpace = ch;
		}
		i++;
	}
	return calls;
}

type BazelQueryToken =
	| { kind: "op"; value: "+" | "-" | "^" }
	| { kind: "lparen" }
	| { kind: "rparen" }
	| { kind: "comma" }
	| { kind: "string"; value: string }
	| { kind: "word"; value: string };

function tokenizeBazelQuery(query: string): BazelQueryToken[] {
	const tokens: BazelQueryToken[] = [];
	let i = 0;
	while (i < query.length) {
		const ch = query[i];
		if (ch === " " || ch === "\t" || ch === "\r" || ch === "\n") {
			i++;
			continue;
		}
		if (ch === "(") {
			tokens.push({ kind: "lparen" });
			i++;
			continue;
		}
		if (ch === ")") {
			tokens.push({ kind: "rparen" });
			i++;
			continue;
		}
		if (ch === ",") {
			tokens.push({ kind: "comma" });
			i++;
			continue;
		}
		if (ch === "+" || ch === "-" || ch === "^") {
			tokens.push({ kind: "op", value: ch });
			i++;
			continue;
		}
		if (ch === "'" || ch === '"') {
			const quote = ch;
			let value = "";
			i++;
			while (i < query.length && query[i] !== quote) {
				if (query[i] === "\\" && i + 1 < query.length) {
					value += query[i + 1];
					i += 2;
				} else {
					value += query[i];
					i++;
				}
			}
			if (i >= query.length) throw new Error(`Unterminated string in Bazel query: ${query}`);
			i++;
			tokens.push({ kind: "string", value });
			continue;
		}
		const start = i;
		while (i < query.length && !/[\s(),+^'"]/.test(query[i])) i++;
		const word = query.slice(start, i);
		if (word === "union") tokens.push({ kind: "op", value: "+" });
		else if (word === "except") tokens.push({ kind: "op", value: "-" });
		else if (word === "intersect") tokens.push({ kind: "op", value: "^" });
		else tokens.push({ kind: "word", value: word });
	}
	return tokens;
}

function cratePatternMatcher(pattern: string): CiClippyTargetMatcher {
	if (pattern === "//crates/..." || pattern === "//...") {
		return () => true;
	}
	const wildcard = /^\/\/crates\/([^/:]+)\/\.\.\.$/.exec(pattern);
	if (wildcard) {
		const expectedCrate = wildcard[1];
		return crate => crate === expectedCrate;
	}
	const pkgAll = /^\/\/crates\/([^/:]+)(?::all)?$/.exec(pattern);
	if (pkgAll) {
		const expectedCrate = pkgAll[1];
		return crate => crate === expectedCrate;
	}
	const exactTarget = /^\/\/crates\/([^/:]+):([^/:]+)$/.exec(pattern);
	if (exactTarget) {
		const expectedCrate = exactTarget[1];
		const expectedTarget = exactTarget[2];
		return (crate, _kind, target) => crate === expectedCrate && target === expectedTarget;
	}
	return () => false;
}

function parseBazelQuery(query: string): CiClippyTargetMatcher {
	const tokens = tokenizeBazelQuery(query);
	let pos = 0;

	function parseUnionDiff(): CiClippyTargetMatcher {
		let left = parseIntersect();
		while (pos < tokens.length) {
			const tok = tokens[pos];
			if (tok.kind === "op" && (tok.value === "+" || tok.value === "-")) {
				pos++;
				const right = parseIntersect();
				const prev = left;
				left =
					tok.value === "+"
						? (c, k, t) => prev(c, k, t) || right(c, k, t)
						: (c, k, t) => prev(c, k, t) && !right(c, k, t);
			} else {
				break;
			}
		}
		return left;
	}

	function parseIntersect(): CiClippyTargetMatcher {
		let left = parsePrimary();
		while (pos < tokens.length) {
			const tok = tokens[pos];
			if (tok.kind === "op" && tok.value === "^") {
				pos++;
				const right = parsePrimary();
				const prev = left;
				left = (c, k, t) => prev(c, k, t) && right(c, k, t);
			} else {
				break;
			}
		}
		return left;
	}

	function parsePrimary(): CiClippyTargetMatcher {
		const tok = tokens[pos];
		if (tok == null) throw new Error(`Unexpected end of Bazel query: ${query}`);
		if (tok.kind === "lparen") {
			pos++;
			const inner = parseUnionDiff();
			if (tokens[pos]?.kind !== "rparen") {
				throw new Error(`Expected ')' in Bazel query: ${query}`);
			}
			pos++;
			return inner;
		}
		if (tok.kind === "word" && tok.value === "kind" && tokens[pos + 1]?.kind === "lparen") {
			pos += 2;
			const patternTok = tokens[pos];
			if (patternTok == null || (patternTok.kind !== "string" && patternTok.kind !== "word")) {
				throw new Error(`Expected kind() regex in Bazel query: ${query}`);
			}
			pos++;
			if (tokens[pos]?.kind !== "comma") {
				throw new Error(`Expected ',' in kind() of Bazel query: ${query}`);
			}
			pos++;
			const inner = parseUnionDiff();
			if (tokens[pos]?.kind !== "rparen") {
				throw new Error(`Expected ')' after kind() in Bazel query: ${query}`);
			}
			pos++;
			const kindRegex = new RegExp(patternTok.value);
			return (c, k, t) => kindRegex.test(`${k} rule`) && inner(c, k, t);
		}
		if (tok.kind === "word" || tok.kind === "string") {
			pos++;
			return cratePatternMatcher(tok.value);
		}
		throw new Error(`Unexpected token in Bazel query: ${query}`);
	}

	const matcher = parseUnionDiff();
	if (pos !== tokens.length) {
		throw new Error(`Unexpected trailing tokens in Bazel query: ${query}`);
	}
	return matcher;
}

function extractShellArg(line: string, start: number): { value: string; end: number } | null {
	let i = start;
	while (i < line.length && (line[i] === " " || line[i] === "\t")) i++;
	if (i >= line.length) return null;
	const ch = line[i];
	if (ch === '"' || ch === "'") {
		const quote = ch;
		let value = "";
		i++;
		while (i < line.length && line[i] !== quote) {
			if (quote === '"' && line[i] === "\\" && i + 1 < line.length) {
				value += line[i + 1];
				i += 2;
			} else {
				value += line[i];
				i++;
			}
		}
		if (i >= line.length) return null;
		return { value, end: i + 1 };
	}
	const wordStart = i;
	while (i < line.length && !/[\s|;&]/.test(line[i])) i++;
	if (i === wordStart) return null;
	return { value: line.slice(wordStart, i), end: i };
}

function extractClippyMatchersFromRun(run: string): CiClippyTargetMatcher[] {
	const matchers: CiClippyTargetMatcher[] = [];
	const normalized = run.replace(/\\\r?\n/g, " ");
	for (const rawLine of normalized.split("\n")) {
		const line = rawLine.trim();
		if (line.length === 0 || line.startsWith("#")) continue;
		// Match `--config=clippy` and `--config=clippy-strict` (not `--config=clippy-ported`).
		if (!/--config=clippy(?:-strict)?(?:\s|$)/.test(line)) continue;

		const queryCmd = /\b(?:bazelisk|bazel)\s+query\b/.exec(line);
		if (queryCmd) {
			let pos = queryCmd.index + queryCmd[0].length;
			let queryArg: string | null = null;
			while (pos < line.length) {
				const arg = extractShellArg(line, pos);
				if (arg == null) break;
				pos = arg.end;
				if (arg.value === "--") {
					const next = extractShellArg(line, pos);
					if (next) queryArg = next.value;
					break;
				}
				if (arg.value.startsWith("-")) continue;
				queryArg = arg.value;
				break;
			}
			if (queryArg != null) {
				matchers.push(parseBazelQuery(queryArg));
			}
			continue;
		}

		const targetPatterns = line.match(/\/\/(?:crates\/[^\s'"]+|\.\.\.)/g);
		if (targetPatterns && targetPatterns.length > 0) {
			const preds = targetPatterns.map(cratePatternMatcher);
			matchers.push((c, k, t) => preds.some(pred => pred(c, k, t)));
		}
	}
	return matchers;
}

async function loadCiClippyMatcher(root: string): Promise<CiClippyTargetMatcher | null> {
	const ciPath = path.join(root, ".github", "workflows", "ci.yml");
	const ciText = await readText(ciPath);
	if (ciText == null) return null;

	const parsed = Bun.YAML.parse(ciText) as {
		jobs?: { rust_validate?: { steps?: Array<{ run?: unknown }> } };
	};
	const steps = parsed?.jobs?.rust_validate?.steps;
	if (!Array.isArray(steps)) {
		return () => false;
	}
	const matchers: CiClippyTargetMatcher[] = [];
	for (const step of steps) {
		if (typeof step?.run === "string") {
			matchers.push(...extractClippyMatchersFromRun(step.run));
		}
	}
	return (crate, kind, target) => matchers.some(matcher => matcher(crate, kind, target));
}

async function checkCoverage(root: string): Promise<Coverage> {
	const cratesDir = path.join(root, "crates");
	let entries: string[];
	try {
		entries = await fs.readdir(cratesDir);
	} catch (err) {
		if (isEnoent(err)) return { covered: [], gaps: [] };
		throw err;
	}
	const ciScheduled = await loadCiClippyMatcher(root);
	const covered: string[] = [];
	const gaps: CoverageGap[] = [];
	for (const name of entries.sort()) {
		const crateDir = path.join(cratesDir, name);
		if (!(await fs.stat(crateDir)).isDirectory()) continue;
		const cargoPath = path.join(crateDir, "Cargo.toml");
		const cargoToml = await readText(cargoPath);
		if (cargoToml == null) continue;
		if (!optsIntoWorkspaceLints(cargoToml)) continue;

		const buildPath = path.join(crateDir, "BUILD.bazel");
		const buildText = await readText(buildPath);
		if (buildText == null) {
			gaps.push({ crate: name, detail: "has no BUILD.bazel" });
			continue;
		}
		const calls = clippyRuleCalls(buildText);
		if (calls.length === 0) {
			gaps.push({
				crate: name,
				detail: `has no ${CLIPPY_RULES.join(", ")} target`,
			});
			continue;
		}
		let crateCovered = true;
		for (const call of calls) {
			const nameAttr = call.stringAttrs?.get("name") ?? "<unnamed>";
			if (call.stringAttrs == null || call.stringAttrs.get("lint_config") !== WORKSPACE_LINTS_LABEL) {
				crateCovered = false;
				gaps.push({
					crate: name,
					detail: `${call.kind} "${nameAttr}" is missing lint_config = "${WORKSPACE_LINTS_LABEL}"`,
				});
			}
			if (ciScheduled != null && !ciScheduled(name, call.kind, nameAttr)) {
				crateCovered = false;
				gaps.push({
					crate: name,
					detail: `${call.kind} "${nameAttr}" is not scheduled by .github/workflows/ci.yml clippy queries`,
				});
			}
		}
		if (crateCovered) covered.push(name);
	}
	return { covered, gaps };
}

function coverageLine(covered: readonly string[]): string {
	return covered.length === 0 ? `${COVERAGE_PREFIX}` : `${COVERAGE_PREFIX} ${covered.join(" ")}`;
}

function reportGaps(coverage: Coverage): void {
	for (const gap of coverage.gaps) {
		console.error(`${GAP_PREFIX} ${gap.crate} ${gap.detail}`);
	}
}

interface Args {
	check: boolean;
	coverageOnly: boolean;
	root: string;
}

function parseArgs(argv: string[]): Args {
	const rootFlag = argv.indexOf("--root");
	let root = repoRoot;
	if (rootFlag !== -1) {
		const value = argv[rootFlag + 1];
		if (value == null || value.startsWith("--")) {
			console.error("--root requires a directory");
			process.exit(2);
		}
		root = path.resolve(value);
	}
	return {
		check: argv.includes("--check"),
		coverageOnly: argv.includes("--coverage"),
		root,
	};
}

const args = parseArgs(process.argv.slice(2));

if (args.coverageOnly) {
	const coverage = await checkCoverage(args.root);
	if (coverage.gaps.length > 0) {
		reportGaps(coverage);
		process.exit(1);
	}
	console.log(coverageLine(coverage.covered));
	process.exit(0);
}

const lints = await loadWorkspaceLints(args.root);
const expected = {
	clippyBazelrc: renderClippyBazelrc(lints),
	lintsBuild: renderLintsBuild(lints),
};
const outputs = [
	{
		label: "bazel/clippy.bazelrc",
		path: path.join(args.root, "bazel", "clippy.bazelrc"),
		text: expected.clippyBazelrc,
	},
	{
		label: "bazel/lints/BUILD.bazel",
		path: path.join(args.root, "bazel", "lints", "BUILD.bazel"),
		text: expected.lintsBuild,
	},
];
const coverage = await checkCoverage(args.root);

if (args.check) {
	let stale = false;
	for (const output of outputs) {
		const current = (await readText(output.path)) ?? "";
		if (current !== output.text) {
			stale = true;
			console.error(
				`${output.label} is stale relative to [workspace.lints] in Cargo.toml.\n` +
					"Run `bun run gen:clippy` and commit the result.",
			);
		}
	}
	if (coverage.gaps.length > 0) reportGaps(coverage);
	if (stale || coverage.gaps.length > 0) process.exit(1);
	for (const output of outputs) {
		console.log(`${output.label} is in sync with Cargo.toml.`);
	}
	console.log(coverageLine(coverage.covered));
} else {
	let wrote = false;
	for (const output of outputs) {
		const current = (await readText(output.path)) ?? "";
		if (current === output.text) continue;
		await Bun.write(output.path, output.text);
		console.log(`Wrote ${output.label}.`);
		wrote = true;
	}
	if (!wrote) console.log("bazel clippy policy already up to date.");
	if (coverage.gaps.length > 0) {
		reportGaps(coverage);
		process.exit(1);
	}
}
