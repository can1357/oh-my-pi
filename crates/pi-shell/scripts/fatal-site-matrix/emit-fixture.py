#!/usr/bin/env python3
"""Emit the committed fixture from a measured site-matrix pass.

The repository keeps one sample per element of every axis the jump model has,
with Bash 5.3.0's own answer as the expected column. Nothing here is chosen
by hand: the rows are picked from the measured pass by axis, and the axis
lists come from the engine's enum declarations.

usage: emit-fixture.py <sites.json> <measured.json> <out.json>
"""

import argparse
import json


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("sites", help="JSON written by gen-sites.py")
    parser.add_argument("measured", help="JSON written by measure-sites.py")
    parser.add_argument("output", help="regression fixture JSON to write")
    args = parser.parse_args()
    fixture = json.load(open(args.sites, encoding="utf-8"))
    measured = {r["id"]: r for r in json.load(open(args.measured, encoding="utf-8"))}
    rows, seen = [], set()

    def take(row_id: str, axis: str, element: str) -> None:
        if row_id in seen:
            rows[[r["id"] for r in rows].index(row_id)]["axes"].append(f"{axis}:{element}")
            return
        m = measured.get(row_id)
        if m is None:
            raise SystemExit(f"emit-fixture: the pass has no row {row_id}")
        for label in ("5.2", "5.3"):
            column = m.get(label)
            if not isinstance(column, dict) or not isinstance(column.get("out"), str) or type(column.get("rc")) is not int:
                raise SystemExit(f"emit-fixture: the pass has no usable Bash {label} column for {row_id}")
        if (m["5.2"]["out"], m["5.2"]["rc"]) != (m["5.3"]["out"], m["5.3"]["rc"]):
            raise SystemExit(f"emit-fixture: Bash 5.2.21 and 5.3.0 differ on {row_id}")
        seen.add(row_id)
        rows.append(
            {
                "id": row_id,
                "axes": [f"{axis}:{element}"],
                "script": m["script"],
                "out": m["5.3"]["out"],
                "status": m["5.3"]["rc"],
            }
        )

    # One row per syntactic construct: together these decide which opcodes the
    # fixture reaches, which is how the `Opcode` axis is covered.
    for c in fixture["constructs"]:
        take(f"construct-{c['name']}-fatal_unset-top-clean", "construct", c["name"])
    # One row per catch context, and per context with a non-zero status at the
    # jump site (the two answers a catch chooses between).
    for c in fixture["contexts"]:
        for prior in ("clean", "prior3"):
            take(f"construct-simple-fatal_unset-{c['name']}-{prior}", "context", c["name"])
    # One row per error raiser, in a context that can tell the codes apart.
    for r in fixture["raisers"]:
        for ctx in (
            "top",
            "top_errexit",
            "exit_trap",
            "exit_trap_errexit",
            "subshell",
            "top_posix",
            "top_posix_errexit",
            "exit_trap_posix",
        ):
            take(f"construct-simple-{r['name']}-{ctx}-clean", "raiser", r["name"])
    # Every declaration builtin kind, in both of its forms.
    for kind, forms in fixture["declarations"].items():
        for i in range(len(forms)):
            for ctx in ("top", "exit_trap"):
                take(f"declare-{kind}{i}-declaration-{ctx}-clean", "declareKind", kind)

    out = {
        "note": (
            "Generated by gen-sites.py + measure-sites.py; the expected column is "
            "Bash 5.3.0's own answer for the same -c string, and Bash 5.2.21 agrees "
            "on every row. Regenerate, never hand-edit."
        ),
        "enums": fixture["enums"],
        "rows": rows,
    }
    json.dump(out, open(args.output, "w", encoding="utf-8"), indent="\t")
    print(f"{len(rows)} fixture rows")


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, KeyError, TypeError) as error:
        raise SystemExit(f"emit-fixture: {error}") from error
