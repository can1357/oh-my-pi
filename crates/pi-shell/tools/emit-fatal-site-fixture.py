#!/usr/bin/env python3
"""Emit the committed fatal-site fixture from a measured pass.

Nothing here is chosen by hand: the rows are picked from the generated matrix
by axis, and the axis lists come from the engine's own enum declarations.

Two columns are recorded per row. `out`/`status` is Bash 5.3.0's own answer for
the same `-c` string, which is what the engine ought to give; Bash 5.2.21 agrees
on every row EXCEPT the no-fork ones (`${ ;}` and `${| ;}`), which it cannot
parse at all — each of those carries `bash_peer_lacks_nofork` and 5.3.0 is the
only answer; any OTHER disagreement ends this script. `engine_out`/
`engine_status` is what the baseline tree answers today, which is what the
committed test asserts: a row where the two columns differ is a site the engine
does not match bash on yet, and the test says so instead of failing. That makes
the fixture a regression gate rather than a wish list -- a row whose answer
moves away from the baseline is named as a regression when the baseline matched
bash, and as a stale fixture when the new answer is bash's.

Which rows:

* the original matrix, as a cover -- one row per syntactic construct, per catch
  context (with and without a non-zero prior status), per error raiser in the
  contexts that tell the codes apart, and per declaration builtin kind in both
  of its forms;
* the carrier matrix, in full -- which frame catches a fatal error depends on
  every one of context, carrier and raiser together, so a cover would not see
  the combinations that matter.

usage: emit-fatal-site-fixture.py <sites.json> <measured.json> <out.json>
                                  [--bash LABEL] [--engine LABEL]
       emit-fatal-site-fixture.py --ids <sites.json>
"""

import argparse
import json
import sys

NOTE = (
	"Generated by tools/gen-fatal-sites.py, tools/measure-fatal-sites.py and "
	"tools/emit-fatal-site-fixture.py. `out`/`status` is Bash 5.3.0's own answer for the "
	"same -c string. Bash 5.2.21 agrees on every row EXCEPT the no-fork ones, which it "
	"cannot parse at all (`${ ;}` and `${| ;}` are 5.3 syntax); each of those carries "
	"`bash_peer_lacks_nofork` and 5.3.0 is the only answer for it. `engine_out`/"
	"`engine_status` is what the baseline tree this pass measured answers; the test "
	"asserts that column and reports a row that moved as a regression (the baseline "
	"matched bash) or as a stale fixture (the new answer is bash's). `axes` lists every "
	"element of every sampled axis, and the in-crate gate requires a row for each. "
	"Regenerate, never hand-edit."
)

# The contexts an error raiser is sampled in: the ones that tell the jump codes
# apart (what the status is, and whether later commands run).
RAISER_CONTEXTS = (
	"top",
	"top_errexit",
	"exit_trap",
	"exit_trap_errexit",
	"subshell",
	"top_posix",
	"top_posix_errexit",
	"exit_trap_posix",
)


def selection(fixture: dict) -> list[tuple[str, str, str]]:
	"""`(row id, axis, element)` of every row the committed fixture takes."""
	want: list[tuple[str, str, str]] = []
	# One row per syntactic construct: together these decide which opcodes the
	# fixture reaches, which is how the `Opcode` axis is covered.
	for c in fixture["constructs"]:
		want.append((f"construct-{c['name']}-fatal_unset-top-clean", "construct", c["name"]))
	# One row per catch context, and per context with a non-zero status at the
	# jump site (the two answers a catch chooses between).
	for c in fixture["contexts"]:
		for prior in ("clean", "prior3"):
			want.append(
				(f"construct-simple-fatal_unset-{c['name']}-{prior}", "context", c["name"])
			)
	# One row per error raiser, in a context that can tell the codes apart.
	for r in fixture["raisers"]:
		for ctx in RAISER_CONTEXTS:
			want.append((f"construct-simple-{r['name']}-{ctx}-clean", "raiser", r["name"]))
	# Every declaration builtin kind, in both of its forms.
	for kind, forms in fixture["declarations"].items():
		for i in range(len(forms)):
			for ctx in ("top", "exit_trap"):
				want.append((f"declare-{kind}{i}-declaration-{ctx}-clean", "declareKind", kind))
	# The carrier matrix in full, with the axes the generator already tagged.
	for row in fixture["rows"]:
		if row["id"].startswith("carrier-"):
			want.append((row["id"], "", ""))
	return want


def main() -> None:
	ap = argparse.ArgumentParser()
	ap.add_argument("--ids", action="store_true", help="print the row ids and exit")
	ap.add_argument("--bash", default="5.3", help="measured column holding Bash 5.3.0")
	ap.add_argument("--bash-peer", default="5.2", help="measured column that must agree")
	ap.add_argument("--engine", default="main", help="measured column holding the baseline tree")
	ap.add_argument("args", nargs="*")
	opts = ap.parse_args()

	if opts.ids:
		if len(opts.args) != 1:
			sys.exit("emit-fatal-site-fixture: --ids wants <sites.json>")
		fixture = json.load(open(opts.args[0]))
		seen = set()
		for row_id, _, _ in selection(fixture):
			if row_id not in seen:
				seen.add(row_id)
				print(row_id)
		return

	if len(opts.args) != 3:
		sys.exit("emit-fatal-site-fixture: wants <sites.json> <measured.json> <out.json>")
	sites, measured_path, outp = opts.args
	fixture = json.load(open(sites))
	measured = {r["id"]: r for r in json.load(open(measured_path))}
	generated = {r["id"]: r for r in fixture["rows"]}

	rows: list[dict] = []
	at: dict[str, int] = {}
	for row_id, axis, element in selection(fixture):
		if row_id in at:
			if axis:
				rows[at[row_id]]["axes"].append(f"{axis}:{element}")
			continue
		m = measured.get(row_id)
		if m is None:
			sys.exit(f"emit-fatal-site-fixture: the pass has no row {row_id}")
		# A measured answer belongs to the script it was measured for. The
		# generator's samples change; an older pass reused against a newer
		# matrix would record a real answer for the wrong text.
		if m["script"] != generated[row_id]["script"]:
			sys.exit(
				f"emit-fatal-site-fixture: row {row_id} was measured for a different "
				"script than the matrix now generates; re-run measure-fatal-sites.py"
			)
		for col in (opts.bash, opts.bash_peer, opts.engine):
			if col not in m:
				sys.exit(f"emit-fatal-site-fixture: row {row_id} has no {col} column")
		# Bash 5.2.21 has no `${ ;}` / `${| ;}`, so every no-fork carrier row
		# is a syntax error there and 5.3.0 is the only answer. That is the
		# one documented class the two may differ on; any other divergence
		# is a measurement to explain, not to record.
		nofork = "${ " in m["script"] or "${|" in m["script"]
		differs = (m[opts.bash]["out"], m[opts.bash]["rc"]) != (
			m[opts.bash_peer]["out"],
			m[opts.bash_peer]["rc"],
		)
		if differs and not nofork:
			sys.exit(
				f"emit-fatal-site-fixture: Bash {opts.bash_peer} and {opts.bash} differ "
				f"on {row_id}, which has no no-fork substitution; explain the row in the "
				"pull request instead of recording one of the two answers"
			)
		at[row_id] = len(rows)
		row = {
			"id": row_id,
			"axes": list(generated[row_id]["axes"]) + ([f"{axis}:{element}"] if axis else []),
			"script": m["script"],
			"out": m[opts.bash]["out"],
			"status": m[opts.bash]["rc"],
			"engine_out": m[opts.engine]["out"],
			"engine_status": m[opts.engine]["rc"],
		}
		if differs:
			row["bash_peer_lacks_nofork"] = True
		rows.append(row)

	axes = {
		"construct": [c["name"] for c in fixture["constructs"]],
		"context": [c["name"] for c in fixture["contexts"]],
		"raiser": [r["name"] for r in fixture["raisers"]],
		"declareKind": list(fixture["declarations"]),
	}
	out = {"note": NOTE, "enums": fixture["enums"], "axes": axes, "rows": rows}
	with open(outp, "w") as fh:
		json.dump(out, fh, indent="\t")
	unmatched = sum(
		1 for r in rows if (r["engine_out"], r["engine_status"]) != (r["out"], r["status"])
	)
	peer = sum(1 for r in rows if r.get("bash_peer_lacks_nofork"))
	print(
		f"{len(rows)} fixture rows; {unmatched} do not match bash at the baseline; "
		f"{peer} are no-fork rows Bash {opts.bash_peer} cannot parse"
	)


main()
