/// Whether `c` is in one of the sorted inclusive `ranges`.
fn within(c: u32, ranges: &[(u32, u32)]) -> bool {
	ranges
		.binary_search_by(|&(lo, hi)| {
			if hi < c {
				std::cmp::Ordering::Less
			} else if lo > c {
				std::cmp::Ordering::Greater
			} else {
				std::cmp::Ordering::Equal
			}
		})
		.is_ok()
}

/// C `wcwidth(c)`: columns `c` takes, -1 for a non-printable character.
pub fn wcwidth(c: char) -> i32 {
	let c = u32::from(c);
	if c == 0 {
		return 0;
	}
	if c < 0x20 || (0x7f..0xa0).contains(&c) {
		return -1;
	}
	if c < 0x300 {
		return 1;
	}
	if within(c, ZERO) {
		return 0;
	}
	if within(c, WIDE) {
		return 2;
	}
	1
}

#[cfg(test)]
mod tests {
	use super::wcwidth;

	#[test]
	fn widths_of_common_characters() {
		assert_eq!(wcwidth('a'), 1);
		assert_eq!(wcwidth('\u{1b}'), -1);
		assert_eq!(wcwidth('\u{301}'), 0);
		assert_eq!(wcwidth('漢'), 2);
		assert_eq!(wcwidth('\u{1F600}'), 2);
		assert_eq!(wcwidth('é'), 1);
	}
}
