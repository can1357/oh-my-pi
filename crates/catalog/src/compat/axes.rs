/// Finds a compatibility axis by its kebab-case directive spelling.
#[must_use]
pub fn axis(key: &str) -> Option<&'static AxisDef> {
	AXES
		.binary_search_by_key(&key, |definition| definition.key)
		.ok()
		.map(|index| &AXES[index])
}
