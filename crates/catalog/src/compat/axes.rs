//! Closed compatibility-directive vocabulary.

use strum::{Display, EnumString, IntoStaticStr};

/// Namespace owning a compatibility axis.
#[derive(Clone, Copy, Debug, Display, EnumString, Eq, IntoStaticStr, PartialEq)]
#[strum(serialize_all = "kebab-case")]
pub enum AxisSet {
	/// Request-wire compatibility.
	Wire,
	/// Thinking-control compatibility.
	Thinking,
	/// Catalog metadata correction.
	Catalog,
}

/// KDL value shape accepted by an axis.
#[derive(Clone, Copy, Debug, Display, EnumString, Eq, IntoStaticStr, PartialEq)]
#[strum(serialize_all = "kebab-case")]
pub enum AxisShape {
	/// Exactly one scalar argument.
	Scalar,
	/// One or more scalar arguments.
	Array,
	/// A child object and no arguments.
	Object,
}

/// Typed resolved wire-policy record family.
#[derive(Clone, Copy, Debug, Display, EnumString, Eq, IntoStaticStr, PartialEq)]
#[strum(serialize_all = "kebab-case")]
pub enum CompatRecord {
	/// `OpenAI` chat completions.
	OpenAi,
	/// `OpenAI` Responses.
	OpenAiResponses,
	/// Anthropic Messages.
	Anthropic,
	/// Bedrock Converse Stream.
	Bedrock,
	/// Devin agent transport.
	Devin,
	/// Google APIs.
	Google,
}

/// One accepted compatibility directive.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct AxisDef {
	/// Kebab-case KDL directive spelling.
	pub key:           &'static str,
	/// Snake-case resolved Rust record field.
	pub resolved_key:  &'static str,
	/// Owning namespace.
	pub set:           AxisSet,
	/// Accepted KDL value shape.
	pub shape:         AxisShape,
	/// Wire record families carrying this field.
	pub records:       &'static [CompatRecord],
	/// Closed string vocabulary, or empty when the scalar type is unrestricted.
	pub values:        &'static [&'static str],
	/// Whether object child keys are copied verbatim instead of normalized.
	pub verbatim_keys: bool,
}

