//! Glyph Protocol client: ships the TUI's private-use icons to the terminal so
//! the nerd symbol preset renders without a patched font installed.
//!
//! Spec: <https://github.com/raphamorim/rio/blob/main/specs/glyph-protocol.md>
//!
//! Transport is APC `ESC _ 25a1 ; <verb> [; k=v]* [; payload] ESC \` with four
//! verbs — `s` (support query), `q` (coverage query), `r` (register), `c`
//! (clear). The session drives the handshake and parses the replies; this
//! module encodes what it sends: `s` behind its DA1 sentinel at startup; on a
//! `glyf`-capable reply every bundled registration in one shot followed by a
//! `q` for [`CONFIRMATION_CODEPOINT`], whose `glossary` answer confirms the
//! bundle landed. Registrations are fire-and-forget (`reply=0`),
//! session-scoped, and confined to the PUA ranges, so they can never restyle
//! real text.
//!
//! The bundle (`glyph-bundle.json`) is generated by
//! `packages/tui/scripts/gen-glyphs.ts` (`bun run gen:glyphs`).

use std::{fmt::Write as _, sync::LazyLock};

use serde::Deserialize;

use crate::tui::types::GlyphProbe;

/// Protocol identifier: U+25A1 WHITE SQUARE as lowercase hex.
const PROTOCOL_ID: &str = "25a1";
const APC: &str = "\x1b_";
const ST: &str = "\x1b\\";

/// Codepoint the handshake queries after registration to confirm the bundle
/// was accepted: the omp mark (`icon.omp`), which the status line always
/// shows.
pub const CONFIRMATION_CODEPOINT: u32 = 0xf0d57;

/// One bundled outline: base64 simple-glyph record plus its scale policy.
#[derive(Deserialize)]
struct Entry {
	/// Base64 OpenType `glyf` simple-glyph record (§8.2 subset).
	glyf:    String,
	/// Fill the cell edge to edge (`size=stretch`, powerline); otherwise
	/// `size=contain`.
	#[serde(default)]
	stretch: bool,
}

/// Generated icon bundle: shared design metrics plus outlines keyed by
/// lowercase hex codepoint, in file order.
#[derive(Deserialize)]
struct Bundle {
	/// Units per em of the source face.
	upm:    u32,
	/// Authored advance width — identical for every glyph of a Mono face.
	aw:     u32,
	/// Authored line height (ascender − descender); outlines are lifted so
	/// y=0 is the descender line.
	lh:     u32,
	glyphs: serde_json::Map<String, serde_json::Value>,
}

static BUNDLE: LazyLock<Bundle> = LazyLock::new(|| {
	serde_json::from_str(include_str!("glyph-bundle.json"))
		.expect("bundled glyph-bundle.json parses")
});

/// Whether `cp` lies in one of the three Private Use Areas the protocol
/// accepts.
pub const fn is_private_use(cp: u32) -> bool {
	matches!(cp, 0xe000..=0xf8ff | 0xf0000..=0xffffd | 0x10_0000..=0x10_fffd)
}

/// `s` verb: doubles as the protocol-detection ping (any reply confirms
/// support).
fn support_query() -> String {
	format!("{APC}{PROTOCOL_ID};s{ST}")
}

/// `q` verb: ask which sources (system font, session glossary) render `cp`.
fn coverage_query(cp: u32) -> String {
	format!("{APC}{PROTOCOL_ID};q;cp={cp:x}{ST}")
}

/// `r` verb for one bundled outline at `cp`. Layout hints follow the bundle's
/// design metrics; `reply=0` suppresses the acknowledgement so bulk startup
/// registration leaves nothing on stdin to drain.
fn write_registration(out: &mut String, cp: u32, entry: &Entry, bundle: &Bundle) {
	debug_assert!(is_private_use(cp), "U+{cp:X} is not a private-use codepoint");
	let size = if entry.stretch { "stretch" } else { "contain" };
	let _ = write!(
		out,
		"{APC}{PROTOCOL_ID};r;cp={cp:x};reply=0;upm={};aw={};lh={};size={size};{}{ST}",
		bundle.upm, bundle.aw, bundle.lh, entry.glyf
	);
}

/// Every bundled icon as one contiguous write. Entries whose key is not a
/// private-use codepoint are skipped (the generator never emits one).
fn bundled_registrations(bundle: &Bundle) -> String {
	let mut out = String::new();
	for (hex, value) in &bundle.glyphs {
		let Ok(cp) = u32::from_str_radix(hex, 16) else {
			continue;
		};
		let Ok(entry) = Entry::deserialize(value) else {
			continue;
		};
		if is_private_use(cp) {
			write_registration(&mut out, cp, &entry, bundle);
		}
	}
	out
}

/// The handshake payloads: the support query, then every registration
/// followed by the confirmation coverage query. Registrations are
/// fire-and-forget (`reply=0`); the coverage query that follows them is the
/// success check — the terminal processes the stream in order, so a
/// `glossary` answer proves the bundle landed.
pub fn probe() -> GlyphProbe {
	static REGISTRATIONS: LazyLock<String> =
		LazyLock::new(|| bundled_registrations(&BUNDLE) + &coverage_query(CONFIRMATION_CODEPOINT));
	GlyphProbe {
		support_query:             support_query(),
		registrations_and_confirm: REGISTRATIONS.clone(),
		confirm_codepoint:         CONFIRMATION_CODEPOINT,
	}
}

#[cfg(test)]
mod tests {
	use base64::{Engine as _, engine::general_purpose::STANDARD};

	use super::*;

	fn metrics() -> Bundle {
		Bundle { upm: 1000, aw: 600, lh: 1320, glyphs: serde_json::Map::new() }
	}

	#[test]
	fn encodes_a_registration_with_bundle_metrics_and_no_reply() {
		let mut out = String::new();
		write_registration(
			&mut out,
			0xe0b0,
			&Entry { glyf: "AAA=".to_owned(), stretch: true },
			&metrics(),
		);
		assert_eq!(
			out,
			"\x1b_25a1;r;cp=e0b0;reply=0;upm=1000;aw=600;lh=1320;size=stretch;AAA=\x1b\\"
		);
		out.clear();
		write_registration(
			&mut out,
			0xf00c,
			&Entry { glyf: "AAA=".to_owned(), stretch: false },
			&metrics(),
		);
		assert!(out.contains(";size=contain;"));
		assert_eq!(support_query(), "\x1b_25a1;s\x1b\\");
		assert_eq!(coverage_query(CONFIRMATION_CODEPOINT), "\x1b_25a1;q;cp=f0d57\x1b\\");
	}

	#[test]
	fn private_use_areas() {
		assert!(is_private_use(0xe000));
		assert!(is_private_use(0xf8ff));
		assert!(!is_private_use(0xf900));
		assert!(is_private_use(0xf0000));
		assert!(!is_private_use(0xffffe));
		assert!(is_private_use(0x10fffd));
		assert!(!is_private_use(0x61));
	}

	#[test]
	fn bundle_ships_only_pua_simple_glyphs_under_the_wire_budget() {
		let mut count = 0;
		for (hex, value) in &BUNDLE.glyphs {
			count += 1;
			assert!(is_private_use(u32::from_str_radix(hex, 16).unwrap()), "{hex}");
			let entry = Entry::deserialize(value).unwrap();
			let record = STANDARD.decode(&entry.glyf).unwrap();
			// Simple-glyph header: numberOfContours > 0 (composites are negative).
			assert!(i16::from_be_bytes([record[0], record[1]]) > 0, "{hex}");
			assert!(record.len() <= 64 * 1024);
		}
		assert!(count > 200);
		let probe = probe();
		assert_eq!(
			probe
				.registrations_and_confirm
				.matches("\x1b_25a1;r;")
				.count(),
			count
		);
		assert!(
			probe
				.registrations_and_confirm
				.ends_with("\x1b_25a1;q;cp=f0d57\x1b\\")
		);
		assert!(
			BUNDLE
				.glyphs
				.contains_key(&format!("{CONFIRMATION_CODEPOINT:x}"))
		);
	}
}
