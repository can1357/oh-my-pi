import { stringifyYamlConfig } from "@oh-my-pi/pi-utils/yaml-config";

/**
 * Environment variable that carries the gateway bearer into the omp process.
 *
 * The generated `models.yml` names this variable as each provider's `apiKey`
 * instead of holding the token: omp runs an `apiKey` that starts with `!` as a
 * shell command and reads one that names a set variable from the environment,
 * so a token written there verbatim could run as a command or resolve to an
 * unrelated variable. The variable's value is used as-is. `agent/omp_local.py`
 * uses the same name.
 */
export const GATEWAY_TOKEN_ENV = "METAHARNESS_GATEWAY_TOKEN";

/**
 * Render a `models.yml` that routes each provider at the host auth gateway.
 * Every value goes through the YAML serializer, so provider ids and the URL stay data.
 */
export function gatewayModelsYaml(providers: Iterable<string>, gatewayUrl: string): string {
	const entries = Object.fromEntries(
		[...new Set(providers)].map(provider => [
			provider,
			{ baseUrl: gatewayUrl, auth: "oauth", transport: "pi-native", apiKey: GATEWAY_TOKEN_ENV },
		]),
	);
	return `# Generated by metaharness — auth via host pm2 gateway.\n${stringifyYamlConfig({ providers: entries })}\n`;
}
