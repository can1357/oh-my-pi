/** Opt-in language for the terminal interface. */
export function uiLanguage(): "en" | "ja" {
	const value = process.env.PI_UI_LANG;
	if (!value || value === "en") return "en";
	if (/^ja(?:[-_]JP)?$/i.test(value)) return "ja";
	throw new Error("Unsupported PI_UI_LANG; use en or ja.");
}

