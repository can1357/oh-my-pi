import { $env, $flag } from "@oh-my-pi/pi-utils";

const SIXEL_START_REGEX = /\x1bP(?:[0-9;]*)q/u;
const SIXEL_END_SEQUENCE = "\x1b\\";
const SIXEL_END_BELL = "\x07";
const SIXEL_SEQUENCE_REGEX = /\x1bP(?:[0-9;]*)q[\s\S]*?(?:\x1b\\|\x07)/gu;
const SIXEL_PLACEHOLDER_PREFIX = "__OMP_SIXEL_SEQUENCE_";

/**
 * Returns whether SIXEL passthrough is explicitly enabled.
 *
 * Both gates must be enabled to preserve SIXEL control sequences:
 * - PI_FORCE_IMAGE_PROTOCOL=sixel
 * - PI_ALLOW_SIXEL_PASSTHROUGH=1
 */
export function isSixelPassthroughEnabled(): boolean {
	const forcedProtocol = $env.PI_FORCE_IMAGE_PROTOCOL?.trim().toLowerCase();
	return forcedProtocol === "sixel" && $flag("PI_ALLOW_SIXEL_PASSTHROUGH");
}
/** Returns true when the text contains a SIXEL start sequence. */
export function containsSixelSequence(text: string): boolean {
	return SIXEL_START_REGEX.test(text);
}

/**
 * Row classifier for a piecewise row stream: reports whether each row belongs
 * to a DCS sequence and carries the in-sequence state across calls, so a
 * payload split over several rows (libsixel emits multi-row payloads) stays
 * classified end to end. A row without a start that follows an open start is
 * part of the sequence until its terminator arrives.
 */
export function createSixelLineClassifier(): (line: string) => boolean {
	let inSequence = false;
	return (line: string) => {
		if (containsSixelSequence(line)) inSequence = true;
		const isSixelRow = inSequence;
		if (inSequence && (line.includes(SIXEL_END_SEQUENCE) || line.includes(SIXEL_END_BELL))) inSequence = false;
		return isSixelRow;
	};
}

/**
 * Returns a boolean mask indicating which lines belong to a SIXEL sequence block.
 * Supports multi-line SIXEL payloads generated by libsixel.
 */
export function getSixelLineMask(lines: readonly string[]): boolean[] {
	const classify = createSixelLineClassifier();
	return lines.map(classify);
}

/** One segment of a raw terminal byte stream split at sixel boundaries. */
export type RawSixelSegment = { kind: "text"; text: string } | { kind: "sixel"; payload: string };

/** Returns true when the line contains a SIXEL start sequence. */
export function isSixelLine(line: string): boolean {
	return containsSixelSequence(line);
}

// An unterminated DCS start is held back until its terminator arrives; this
// bounds that hold so a terminator-less stream cannot grow without limit.
const MAX_HELD_SIXEL_TAIL_CHARS = 8 * 1024 * 1024;

/**
 * Splits a raw terminal byte stream into text segments and complete sixel
 * payloads, holding an unterminated start across calls so a DCS split over
 * chunk boundaries is never fed to a parser that swallows strings: the vterm
 * used by PTY replay would consume every byte up to a stray terminator and
 * silently drop the rows in between.
 */
export function createRawSixelExtractor(): (chunk: string) => RawSixelSegment[] {
	let held = "";
	return (chunk: string) => {
		const buffer = held + chunk;
		held = "";
		const segments: RawSixelSegment[] = [];
		let cursor = 0;
		// The module-level scan regex is shared with the sanitizer's replace();
		// restart the scan from the head of this buffer.
		SIXEL_SEQUENCE_REGEX.lastIndex = 0;
		for (const match of buffer.matchAll(SIXEL_SEQUENCE_REGEX)) {
			const index = match.index ?? 0;
			if (index > cursor) segments.push({ kind: "text", text: buffer.slice(cursor, index) });
			segments.push({ kind: "sixel", payload: match[0] });
			cursor = index + match[0].length;
		}
		const rest = buffer.slice(cursor);
		const start = rest.search(SIXEL_START_REGEX);
		if (start >= 0) {
			if (start > 0) segments.push({ kind: "text", text: rest.slice(0, start) });
			const tail = rest.slice(start);
			held = tail.length > MAX_HELD_SIXEL_TAIL_CHARS ? "" : tail;
		} else if (rest.length > 0) {
			segments.push({ kind: "text", text: rest });
		}
		return segments;
	};
}

/**
 * Sanitizes text while preserving embedded SIXEL sequences when passthrough is enabled.
 */
export function sanitizeWithOptionalSixelPassthrough(text: string, sanitize: (text: string) => string): string {
	if (!isSixelPassthroughEnabled() || !containsSixelSequence(text)) {
		return sanitize(text);
	}

	const preservedSequences: string[] = [];
	const tokenized = text.replace(SIXEL_SEQUENCE_REGEX, match => {
		const token = `${SIXEL_PLACEHOLDER_PREFIX}${preservedSequences.length}__`;
		preservedSequences.push(match);
		return token;
	});

	const sanitized = sanitize(tokenized);
	return sanitized.replace(/__OMP_SIXEL_SEQUENCE_(\d+)__/gu, (_, indexText: string) => {
		const index = Number.parseInt(indexText, 10);
		return preservedSequences[index] ?? "";
	});
}
