/**
 * Glyph Protocol client: ships the private-use icons to terminals that
 * implement it (rio), so the nerd symbol preset renders without a patched
 * font. Transport: APC `ESC _ 25a1 ; <verb> [; k=v]* [; payload] ESC \`.
 * The driver sends `s` (support) behind a DA1 sentinel; a `glyf`-capable
 * answer gets every bundled outline registered (`r`, `reply=0`) followed by a
 * `q` for {@link GLYPH_CONFIRMATION_CODEPOINT}, whose `glossary` coverage
 * confirms the bundle landed.
 *
 * Spec: https://github.com/raphamorim/rio/blob/main/specs/glyph-protocol.md
 * `glyph-bundle.json` is generated by `packages/tui/scripts/gen-glyphs.ts` (`bun run gen:glyphs`).
 */
import bundle from "./glyph-bundle.json" with { type: "json" };

const PREFIX = "\x1b_25a1;";
const ST = "\x1b\\";

interface GlyphBundle {
	readonly upm: number;
	readonly aw: number;
	readonly lh: number;
	readonly glyphs: Readonly<Record<string, { readonly glyf: string; readonly stretch?: boolean }>>;
}

const GLYPHS: GlyphBundle = bundle;

/** The omp mark (the status line always shows it): its coverage confirms the registration. */
export const GLYPH_CONFIRMATION_CODEPOINT = 0xf0d57;

/** A decoded Glyph Protocol reply. */
export type GlyphReply =
	| { readonly verb: "s"; readonly formats: readonly string[] }
	| { readonly verb: "q"; readonly cp: number; readonly coverage: readonly string[] }
	| { readonly verb: "r" | "c"; readonly status: number };

/** The support query. */
export const GLYPH_SUPPORT_QUERY = `${PREFIX}s${ST}`;

/** Every bundled outline registered, then the confirmation coverage query. */
export function glyphRegistrations(): string {
	let out = "";
	for (const hex in GLYPHS.glyphs) {
		const entry = GLYPHS.glyphs[hex]!;
		const size = entry.stretch ? "stretch" : "contain";
		out += `${PREFIX}r;cp=${hex};reply=0;upm=${GLYPHS.upm};aw=${GLYPHS.aw};lh=${GLYPHS.lh};size=${size};${entry.glyf}${ST}`;
	}
	return `${out}${PREFIX}q;cp=${GLYPH_CONFIRMATION_CODEPOINT.toString(16)}${ST}`;
}

/** Decode `seq` (a complete APC string), or null when it is not a Glyph Protocol reply. */
export function parseGlyphReply(seq: string): GlyphReply | null {
	if (!seq.startsWith(PREFIX) || !seq.endsWith(ST)) return null;
	const [verb, ...parts] = seq.slice(PREFIX.length, -ST.length).split(";");
	const params: Record<string, string> = {};
	for (const part of parts) {
		const eq = part.indexOf("=");
		if (eq > 0) params[part.slice(0, eq)] = part.slice(eq + 1);
	}
	const list = (value: string | undefined): string[] => (value ? value.split(",") : []);
	switch (verb) {
		case "s":
			return { verb, formats: list(params.fmt) };
		case "q": {
			const cp = Number.parseInt(params.cp ?? "", 16);
			return Number.isFinite(cp) ? { verb, cp, coverage: list(params.status) } : null;
		}
		case "r":
		case "c": {
			const status = Number.parseInt(params.status ?? "", 10);
			return Number.isFinite(status) ? { verb, status } : null;
		}
		default:
			return null;
	}
}
