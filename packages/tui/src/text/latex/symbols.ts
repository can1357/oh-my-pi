const ITALIC_SPECIAL: Readonly<Record<string, string>> = { h: "ℎ" };
const FRAK_SPECIAL: Readonly<Record<string, string>> = { C: "ℭ", H: "ℌ", I: "ℑ", R: "ℜ", Z: "ℨ" };

/** A letter or digit in a Mathematical Alphanumeric Symbols alphabet. */
function alphabet(
	char: string,
	upper: number,
	lower: number | undefined,
	digit: number | undefined,
	special: Readonly<Record<string, string>>,
): string {
	const fixed = special[char];
	if (fixed !== undefined) return fixed;
	const code = char.charCodeAt(0);
	if (char.length !== 1) return char;
	if (code >= 0x41 && code <= 0x5a) return String.fromCodePoint(upper + code - 0x41);
	if (lower !== undefined && code >= 0x61 && code <= 0x7a) return String.fromCodePoint(lower + code - 0x61);
	if (digit !== undefined && code >= 0x30 && code <= 0x39) return String.fromCodePoint(digit + code - 0x30);
	return char;
}

/** `char` in a math alphabet (`\mathbb`, `\mathcal`, `\mathfrak`, `\mathscr`). */
export function fontGlyph(font: "bb" | "cal" | "frak" | "scr" | "bold" | "italic", char: string): string {
	switch (font) {
		case "bold":
			return alphabet(char, 0x1d400, 0x1d41a, 0x1d7ce, NO_SPECIAL);
		case "italic":
			return alphabet(char, 0x1d434, 0x1d44e, undefined, ITALIC_SPECIAL);
		case "bb":
			return alphabet(char, 0x1d538, 0x1d552, 0x1d7d8, BB_SPECIAL);
		case "cal":
		case "scr":
			return alphabet(char, 0x1d49c, 0x1d4b6, undefined, CAL_SPECIAL);
		case "frak":
			return alphabet(char, 0x1d504, 0x1d51e, undefined, FRAK_SPECIAL);
	}
}
